                                <?php echo esc_html($country); ?> (<?php echo esc_html($info['language']); ?>)
                            </option>
                        <?php endforeach; ?>
                    </select>
                </div>
                <div>
                    <label><strong>Filter by City:</strong></label><br>
                    <select id="city-select" style="min-width:200px;padding:5px;">
                        <option value="">-- All Cities --</option>
                        <?php if (isset($data[$selected_country])): ?>
                            <?php foreach ($data[$selected_country]['cities'] as $city): ?>
                                <option value="<?php echo esc_attr($city); ?>"><?php echo esc_html($city); ?></option>
