<script>
jQuery(function($){
	function escHtml(s){ return $('<div>').text(s||'').html(); }
	function showNotice(m,t){ var $n=$('#automation-notice'); $n.text(m).removeClass('success error').addClass(t||'success').show(); setTimeout(function(){ $n.fadeOut(); },4000); }

	// Toggle switches
	$('.auto-toggle').on('change',function(){
		var opt=$(this).data('option'), val=$(this).is(':checked')?'1':'0';
		$.post(ajaxurl,{action:'sgc_crm_save_option',nonce:SGC_CRM.nonce,option_name:opt,option_value:val},function(r){
			showNotice(r.success?'<?php esc_html_e("Saved.","sgc-smart-crm"); ?>':'<?php esc_html_e("Error.","sgc-smart-crm"); ?>',r.success?'success':'error');
		});
	});

	// Load sequences
	function loadSequences(){
		$.post(ajaxurl,{action:'sgc_crm_get_sequences',nonce:SGC_CRM.nonce},function(r){
			if(!r.success) return;
			var html='';
			if(!r.data||!r.data.length){ html='<em><?php esc_html_e("No custom sequences yet.","sgc-smart-crm"); ?></em>'; }
			else {
				html='<table class="sgc-crm-table"><thead><tr><th>Name</th><th>Trigger</th><th>Delay</th><th>Sent</th><th>Active</th><th>Actions</th></tr></thead><tbody>';
				r.data.forEach(function(s){
					html+='<tr><td>'+escHtml(s.name)+'</td><td>'+escHtml(s.trigger_event)+'</td><td>'+s.delay_hours+'h</td><td>'+s.sent_count+'</td>'
						+'<td><label class="sgc-crm-toggle"><input type="checkbox" class="seq-toggle" data-id="'+s.id+'" '+(s.active=='1'?'checked':'')+'><span class="sgc-crm-toggle-slider"></span></label></td>'
						+'<td><button class="sgc-btn-icon edit-seq" data-id="'+s.id+'">✏️</button> <button class="sgc-btn-icon delete-seq" data-id="'+s.id+'">🗑️</button></td></tr>';
				});
				html+='</tbody></table>';
			}
			$('#sequences-list').html(html);
		});
	}
	loadSequences();

	// Load log
	$.post(ajaxurl,{action:'sgc_crm_get_auto_log',nonce:SGC_CRM.nonce},function(r){
		if(!r.success) return;
		var tbody='';
		if(!r.data||!r.data.length){ tbody='<tr><td colspan="5" style="text-align:center;padding:16px"><?php esc_html_e("No log entries yet.","sgc-smart-crm"); ?></td></tr>'; }
		else r.data.forEach(function(l){
			var badge = l.status==='sent'?'<span class="sgc-badge green">sent</span>':l.status==='failed'?'<span class="sgc-badge red">failed</span>':'<span class="sgc-badge grey">'+l.status+'</span>';
			tbody+='<tr><td>'+escHtml(l.sequence_name||l.trigger_event)+'</td><td>'+escHtml(l.email)+'</td><td>'+escHtml(l.trigger_event)+'</td><td>'+escHtml(l.scheduled_at)+'</td><td>'+badge+'</td></tr>';
		});
		$('#auto-log-tbody').html(tbody);
	});

	// New sequence
	$('#btn-new-sequence').on('click',function(){
		$('#seq-id').val(''); $('#seq-modal-title').text('<?php esc_html_e("New Sequence","sgc-smart-crm"); ?>');
		$('#seq-name,#seq-subject,#seq-body').val(''); $('#seq-delay').val(24); $('#seq-trigger').val('new_order');
		$('#sequence-modal').show();
	});

	// Edit seq
	$(document).on('click','.edit-seq',function(){
		var id=$(this).data('id');
		$.post(ajaxurl,{action:'sgc_crm_get_sequences',nonce:SGC_CRM.nonce},function(r){
			if(!r.success) return;
			var seq = r.data.find(function(s){ return s.id==id; });
			if(!seq) return;
			$('#seq-id').val(seq.id); $('#seq-modal-title').text('<?php esc_html_e("Edit Sequence","sgc-smart-crm"); ?>');
			$('#seq-name').val(seq.name); $('#seq-trigger').val(seq.trigger_event);
			$('#seq-delay').val(seq.delay_hours); $('#seq-subject').val(seq.subject); $('#seq-body').val(seq.body_html);
			$('#sequence-modal').show();
		});
	});

	// Save seq
	$('#btn-save-seq').on('click',function(){
		$.post(ajaxurl,{action:'sgc_crm_save_sequence',nonce:SGC_CRM.nonce,
			id:$('#seq-id').val(), name:$('#seq-name').val(), trigger_event:$('#seq-trigger').val(),
			delay_hours:$('#seq-delay').val(), subject:$('#seq-subject').val(), body_html:$('#seq-body').val(), active:1
		},function(r){
			if(r.success){ $('#sequence-modal').hide(); showNotice('<?php esc_html_e("Saved.","sgc-smart-crm"); ?>'); loadSequences(); }
			else showNotice(r.data,'error');
		});
	});

	// Toggle
	$(document).on('change','.seq-toggle',function(){
		$.post(ajaxurl,{action:'sgc_crm_toggle_sequence',nonce:SGC_CRM.nonce,id:$(this).data('id')},function(r){
			showNotice(r.success?'<?php esc_html_e("Updated.","sgc-smart-crm"); ?>':'<?php esc_html_e("Error.","sgc-smart-crm"); ?>',r.success?'success':'error');
		});
	});

	// Delete
	$(document).on('click','.delete-seq',function(){
		if(!confirm(SGC_CRM.confirm_delete)) return;
		$.post(ajaxurl,{action:'sgc_crm_delete_sequence',nonce:SGC_CRM.nonce,id:$(this).data('id')},function(r){
			if(r.success){ showNotice('<?php esc_html_e("Deleted.","sgc-smart-crm"); ?>'); loadSequences(); }
		});
	});

	$(document).on('click','.sgc-crm-modal-close',function(){ $('#'+$(this).data('modal')).hide(); });
	$(document).on('click','.sgc-crm-modal',function(e){ if($(e.target).hasClass('sgc-crm-modal')) $(this).hide(); });
});
</script>
