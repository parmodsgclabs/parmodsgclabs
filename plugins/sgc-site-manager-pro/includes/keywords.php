    function copyAllKeywords() {
        const kws = [...document.querySelectorAll('.kw-text')].map(el => el.dataset.kw).join('\n');
        navigator.clipboard.writeText(kws).then(() => alert('✅ All keywords copied!'));
    }
    function exportCSV() {
        const rows = [['#','Keyword']];
        document.querySelectorAll('.sgclabs-keyword-row').forEach((row, i) => {
            rows.push([i+1, row.querySelector('.kw-text').dataset.kw]);
        });
        const csv = rows.map(r => r.map(c => '"'+c+'"').join(',')).join('\n');
        const blob = new Blob([csv], {type:'text/csv'});
        const a = document.createElement('a');
        a.href = URL.createObjectURL(blob);
        a.download = 'sgclabs-keywords.csv';
        a.click();
    }
    </script>
    <?php
}
