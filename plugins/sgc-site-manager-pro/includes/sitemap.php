// Only activate when RankMath is NOT present
// (if RankMath active, it handles its own sitemaps)
function sgclabs_sitemap_should_run(): bool {
    return get_option('sgclabs_sitemap_active', '0') === '1'
        && !defined('RANK_MATH_VERSION')
        && !defined('WPSEO_VERSION');
}

// ---- REWRITE RULES ----
// FIX: Always register query vars + rewrite rules (even when inactive)
// so WordPress doesn't eat the URL before we can check if active.
// The actual serving is still gated by sgclabs_sitemap_should_run().
add_action('init', 'sgclabs_sitemap_rewrite_rules');
function sgclabs_sitemap_rewrite_rules() {
    // Always register query vars
    add_filter('query_vars', function($vars) {
        $vars[] = 'sgclabs_sitemap_type';
        $vars[] = 'sgclabs_sitemap_page';
        return $vars;
    });

    if (!sgclabs_sitemap_should_run()) return;

    // Master index
    add_rewrite_rule('^sitemap_index\.xml$', 'index.php?sgclabs_sitemap_type=index', 'top');

    // Post-type sitemaps: product-sitemap.xml, page-sitemap.xml, post-sitemap.xml
    // product_cat → product_cat-sitemap.xml uses underscore which is captured by [a-z0-9_-]+
    add_rewrite_rule('^([a-z0-9_-]+)-sitemap([0-9]*)\.xml$',
        'index.php?sgclabs_sitemap_type=$matches[1]&sgclabs_sitemap_page=$matches[2]', 'top');
}

// Auto-flush rewrite rules when sitemap toggled OR on plugin init if needed
add_action('update_option_sgclabs_sitemap_active', function($old, $new) {
    flush_rewrite_rules(false);
}, 10, 2);

// Also flush once after plugin update if rewrite hash doesn't match
add_action('init', function() {
    if (get_option('sgclabs_sitemap_active','0') !== '1') return;
    $hash = md5(home_url() . get_option('sgclabs_sitemap_active','0'));
    if (get_option('sgclabs_sitemap_rewrite_hash','') !== $hash) {
        flush_rewrite_rules(false);
        update_option('sgclabs_sitemap_rewrite_hash', $hash);
    }
}, 99);

// ---- SERVE SITEMAP ----
add_action('template_redirect', 'sgclabs_serve_sitemap_xml', 1);
function sgclabs_serve_sitemap_xml() {
    if (!sgclabs_sitemap_should_run()) return;

    $type = get_query_var('sgclabs_sitemap_type');
    if (!$type) return;

    $page = max(1, intval(get_query_var('sgclabs_sitemap_page') ?: 1));

    header('Content-Type: application/xml; charset=UTF-8');
    header('X-Robots-Tag: noindex, follow');
    header('Cache-Control: max-age=3600');

    if ($type === 'index') {
        echo sgclabs_build_sitemap_index();
    } else {
        echo sgclabs_build_sitemap_entries($type, $page);
    }
    exit;
}

// ---- BUILD INDEX ----
function sgclabs_build_sitemap_index(): string {
    $sitemaps = [
        ['name' => 'product',      'label' => 'Products'],
        ['name' => 'page',         'label' => 'Pages'],
        ['name' => 'post',         'label' => 'Posts'],
        ['name' => 'product_cat',  'label' => 'Product Categories'],
        ['name' => 'product_tag',  'label' => 'Product Tags'],
    ];

    // Add custom taxonomies
    $custom_taxes = get_taxonomies(['public' => true, '_builtin' => false], 'objects');
    foreach ($custom_taxes as $tax) {
        if (in_array($tax->name, ['product_cat', 'product_tag', 'post_tag', 'category'])) continue;
        $sitemaps[] = ['name' => $tax->name, 'label' => $tax->label];
    }

    // Add category, post_tag for blog
    $sitemaps[] = ['name' => 'category', 'label' => 'Categories'];
    $sitemaps[] = ['name' => 'post_tag',  'label' => 'Tags'];

    $xml  = '<?xml version="1.0" encoding="UTF-8"?>' . "\n";
    $xml .= '<?xml-stylesheet type="text/xsl" href="' . esc_url(plugin_dir_url(dirname(__FILE__)) . 'assets/sitemap.xsl') . '"?>' . "\n";
    $xml .= '<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' . "\n";
    $xml .= '<!-- Generated by SGC LABS® Site Manager Pro -->' . "\n";

    foreach ($sitemaps as $s) {
        $count = sgclabs_sitemap_count($s['name']);
        if ($count === 0) continue;

        $pages = max(1, ceil($count / 200));
        for ($p = 1; $p <= $pages; $p++) {
            $suffix = $p > 1 ? $p : '';
            $url    = home_url('/' . $s['name'] . '-sitemap' . $suffix . '.xml');
            $xml   .= "  <sitemap>\n";
            $xml   .= "    <loc>" . esc_url($url) . "</loc>\n";
            $xml   .= "    <lastmod>" . date('Y-m-d') . "</lastmod>\n";
            $xml   .= "  </sitemap>\n";
        }
    }

    $xml .= '</sitemapindex>';
    return $xml;
}

// ---- COUNT ENTRIES ----
function sgclabs_sitemap_count(string $type): int {
    // FIX: Check post_type FIRST — WooCommerce registers 'product' as both post_type AND taxonomy
    // so taxonomy_exists('product') returns true, causing 0 results
    if (post_type_exists($type)) {
        $count = wp_count_posts($type);
        return (int)($count->publish ?? 0);
    }

    // Then check taxonomy (product_cat, product_tag, category, post_tag, custom taxes)
    if (taxonomy_exists($type)) {
        $terms = get_terms(['taxonomy' => $type, 'hide_empty' => true, 'fields' => 'count']);
        return is_wp_error($terms) ? 0 : (int)$terms;
    }

    return 0;
}

// ---- BUILD ENTRIES ----
function sgclabs_build_sitemap_entries(string $type, int $page): string {
    $per_page = 200;
    $offset   = ($page - 1) * $per_page;

    $xml  = '<?xml version="1.0" encoding="UTF-8"?>' . "\n";
    $xml .= '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"' . "\n";
    $xml .= '        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">' . "\n";
    $xml .= '<!-- Generated by SGC LABS® Site Manager Pro -->' . "\n";

    // Taxonomy sitemap — check post_type first (WooCommerce registers 'product' as both)
    if (!post_type_exists($type) && taxonomy_exists($type)) {
        $terms = get_terms([
            'taxonomy'   => $type,
            'hide_empty' => true,
            'number'     => $per_page,
            'offset'     => $offset,
            'orderby'    => 'count',
            'order'      => 'DESC',
        ]);

        if (!is_wp_error($terms)) {
            foreach ($terms as $term) {
                $url = get_term_link($term);
                if (is_wp_error($url)) continue;
                $xml .= sgclabs_sitemap_url($url, date('Y-m-d'), '0.6', 'weekly');
            }
        }
        $xml .= '</urlset>';
        return $xml;
    }

    // Post-type sitemap
    if (!post_type_exists($type)) {
        $xml .= '</urlset>';
        return $xml;
    }

    global $wpdb;
    $posts = $wpdb->get_results($wpdb->prepare(
        "SELECT ID, post_modified, post_type FROM {$wpdb->posts}
         WHERE post_type = %s AND post_status = 'publish'
         ORDER BY post_modified DESC
         LIMIT %d OFFSET %d",
        $type, $per_page, $offset
    ));

    $priority = $type === 'product' ? '0.8' : '0.6';
    $changefreq = $type === 'product' ? 'weekly' : 'monthly';

    foreach ($posts as $post) {
        $url      = get_permalink($post->ID);
        $modified = date('Y-m-d', strtotime($post->post_modified));

        // Image data for products
        $image_xml = '';
        if ($type === 'product') {
            $thumb_id  = get_post_thumbnail_id($post->ID);
            $thumb_url = $thumb_id ? wp_get_attachment_image_url($thumb_id, 'large') : '';
            $title     = htmlspecialchars(get_the_title($post->ID), ENT_XML1 | ENT_QUOTES, 'UTF-8');
            if ($thumb_url) {
                $image_xml  = "    <image:image>\n";
                $image_xml .= "      <image:loc>" . esc_url($thumb_url) . "</image:loc>\n";
                $image_xml .= "      <image:title>" . $title . "</image:title>\n";
                $image_xml .= "    </image:image>\n";
            }
        }

        $xml .= sgclabs_sitemap_url($url, $modified, $priority, $changefreq, $image_xml);
    }

    // Homepage in page sitemap
    if ($type === 'page' && $page === 1) {
        $xml .= sgclabs_sitemap_url(home_url('/'), date('Y-m-d'), '1.0', 'daily');
    }

    $xml .= '</urlset>';
    return $xml;
}

// ---- URL HELPER ----
function sgclabs_sitemap_url(string $loc, string $lastmod, string $priority, string $changefreq, string $extra = ''): string {
    $out  = "  <url>\n";
    $out .= "    <loc>" . esc_url($loc) . "</loc>\n";
    $out .= "    <lastmod>" . esc_html($lastmod) . "</lastmod>\n";
    $out .= "    <changefreq>" . esc_html($changefreq) . "</changefreq>\n";
    $out .= "    <priority>" . esc_html($priority) . "</priority>\n";
    if ($extra) $out .= $extra;
    $out .= "  </url>\n";
    return $out;
}

// ---- FLUSH REWRITE ON TOGGLE ----
add_action('update_option_sgclabs_sitemap_active', function() {
    flush_rewrite_rules();
}, 10, 0);

// ---- ROBOTS.TXT — add sitemap reference ----
add_filter('robots_txt', function($output) {
    if (!sgclabs_sitemap_should_run()) return $output;
    $sitemap_line = 'Sitemap: ' . home_url('/sitemap_index.xml');
    if (strpos((string)$output, $sitemap_line) === false) {
        $output .= "\n" . $sitemap_line . "\n";
    }
    return $output;
}, 20);

